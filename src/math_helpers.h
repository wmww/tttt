#pragma once

static inline int imax(int a, int b) {
    return a > b ? a : b;
}

static inline int imin(int a, int b) {
    return a < b ? a : b;
}

static inline unsigned umax(unsigned a, unsigned b) {
    return a > b ? a : b;
}

static inline unsigned umin(unsigned a, unsigned b) {
    return a < b ? a : b;
}
