#!/usr/bin/env python3
"""Writes the C file that embeds the standard library (thirdparty/lib/*.d.ts) in the binary: each file's text as a string
literal, and the table embedded_libs.h declares, sorted by name. Run by the build (src/meson.build's custom_target):
python3 src/embedded_libs.py LIB_DIR OUT.c DEPFILE. The depfile names every file read and the directory itself, so a
changed, added or removed lib file rebuilds it"""
import os
import sys

lib_dir, out_path, dep_path = sys.argv[1:4]
names = sorted(n for n in os.listdir(lib_dir) if n.endswith('.d.ts'))

# Bytes a string literal can hold as they are: printable ASCII but the escapes' own characters (and `?`: no trigraphs)
plain = [chr(b) if 0x20 <= b < 0x7f and chr(b) not in '\\"?' else None for b in range(256)]
escapes = {ord('\\'): '\\\\', ord('"'): '\\"', ord('?'): '\\?', ord('\t'): '\\t'}


def literal(data):
    """data as string literal lines, one per source line"""
    lines = data.split(b'\n')
    out = []
    for i, line in enumerate(lines):
        last = i == len(lines) - 1
        if last and not line:
            break
        parts = []
        for b in line:
            c = plain[b]
            # (Octal escapes are always three digits: a digit after one can't extend it)
            parts.append(c if c is not None else escapes.get(b) or '\\%03o' % b)
        out.append('    "' + ''.join(parts) + ('' if last else '\\n') + '"')
    return '\n'.join(out) if out else '    ""'


chunks = [
    '// Generated by src/embedded_libs.py from thirdparty/lib at build time: the standard library in the binary',
    '#include "embedded_libs.h"',
    '',
    '// (Every file is one literal, longer than ISO C asks compilers to support)',
    '#pragma GCC diagnostic ignored "-Woverlength-strings"',
    '',
]
for i, name in enumerate(names):
    with open(os.path.join(lib_dir, name), 'rb') as f:
        data = f.read()
    assert b'\0' not in data, name
    chunks.append('static char const lib_%d[] =\n%s;' % (i, literal(data)))
chunks.append('')
chunks.append('EmbeddedLib const embedded_libs[] = {')
for i, name in enumerate(names):
    chunks.append('    { "%s", lib_%d, sizeof lib_%d - 1 },' % (name, i, i))
chunks.append('};')
chunks.append('u32 const embedded_lib_count = %d;' % len(names))
chunks.append('')

with open(out_path, 'w') as f:
    f.write('\n'.join(chunks))


def dep_escape(path):
    return path.replace('\\', '\\\\').replace(' ', '\\ ').replace('$', '$$')


with open(dep_path, 'w') as f:
    deps = [os.path.join(lib_dir, n) for n in names] + [lib_dir, os.path.abspath(__file__)]
    f.write(dep_escape(out_path) + ': ' + ' '.join(dep_escape(d) for d in deps) + '\n')
